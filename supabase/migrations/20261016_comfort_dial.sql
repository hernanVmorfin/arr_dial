-- Comfort Dial: turns (held gifts), claimed wins, and the one-a-month free year.
-- Run once in the Supabase SQL editor for project dienlkpgmgetkkdyduap (the Instant Pricing project). Safe to re-run:
-- it only creates objects that don't exist yet and never touches other tables.
--
-- New names (comfort_dial_*) on purpose: the earlier PR #10 migration created `dial_entries` with a different shape.
-- If that table exists and is empty, it can be dropped; nothing reads it.
--
-- The rules live in constraints, so they hold when two people turn the dial at the same instant:
--   * one gift per phone                      (comfort_dial_entries.phone unique)
--   * one claimed free year per month         (partial unique index on mem_month)
--   * one free year per household, ever       (partial unique index on household_key)
--   * one hold on a month's free year at a time (comfort_dial_memberships primary key; the API swaps an expired hold
--     with a compare-and-set update, never a blind write)
-- RLS is on with no policies: only the server's secret key can read or write, same as the property tables.

create table if not exists public.comfort_dial_turns (
  id          uuid primary key,                -- also the visitor's claim token; generated by the server
  gift        text not null check (gift in ('svc20', 'duct50', 'wh50', 'call', 'mem')),
  mem_month   text,                            -- 'YYYY-MM' when gift = 'mem'
  ip          text,
  device      text,                            -- random id the browser keeps in localStorage
  created_at  timestamptz not null default now(),
  held_until  timestamptz not null,
  claimed_at  timestamptz,
  entry_id    uuid,
  constraint comfort_dial_turns_mem_month check ((gift = 'mem') = (mem_month is not null))
);
create index if not exists comfort_dial_turns_ip on public.comfort_dial_turns (ip, created_at desc);
create index if not exists comfort_dial_turns_device on public.comfort_dial_turns (device, created_at desc);

create table if not exists public.comfort_dial_memberships (
  mem_month   text primary key,                -- 'YYYY-MM'
  turn_id     uuid not null,                   -- the turn holding (or that claimed) this month's free year
  held_until  timestamptz not null,
  claimed_at  timestamptz
);

create table if not exists public.comfort_dial_entries (
  id              uuid primary key default gen_random_uuid(),
  code            text not null,
  turn_id         uuid references public.comfort_dial_turns (id),
  phone           text not null,               -- 10 digits
  gift            text not null check (gift in ('svc20', 'duct50', 'wh50', 'call', 'mem')),
  mem_month       text,
  first_name      text,
  address         text,
  zip             text,
  household_key   text,                        -- pk:<property_key> for a free-year winner matched to a county record
  sms_marketing   boolean not null default false,   -- ticked "text me a reminder and offers"
  utm             jsonb,
  page            text,
  ip              text,
  monday_item_id  text,
  created_at      timestamptz not null default now(),
  expires_at      timestamptz not null,
  redeemed_at     timestamptz,
  redeemed_note   text,
  constraint comfort_dial_entries_code_key unique (code),
  constraint comfort_dial_entries_phone_key unique (phone),
  constraint comfort_dial_entries_turn_key unique (turn_id),
  constraint comfort_dial_entries_mem_month check ((gift = 'mem') = (mem_month is not null)),
  constraint comfort_dial_entries_mem_household check (gift <> 'mem' or household_key is not null)
);
create unique index if not exists comfort_dial_entries_one_membership_per_month
  on public.comfort_dial_entries (mem_month) where gift = 'mem';
create unique index if not exists comfort_dial_entries_one_membership_per_household
  on public.comfort_dial_entries (household_key) where gift = 'mem';
create index if not exists comfort_dial_entries_ip on public.comfort_dial_entries (ip, created_at desc);
create index if not exists comfort_dial_entries_monday on public.comfort_dial_entries (monday_item_id);

alter table public.comfort_dial_turns enable row level security;
alter table public.comfort_dial_memberships enable row level security;
alter table public.comfort_dial_entries enable row level security;
revoke all on public.comfort_dial_turns, public.comfort_dial_memberships, public.comfort_dial_entries from anon, authenticated;
